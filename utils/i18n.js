function getLocale(req) {
    // Priority: Query Param > Cookie > Default 'tr'
    if (req.query.lang && ['tr', 'en'].includes(req.query.lang)) {
        return req.query.lang;
    }

    // Parse cookie manually since we might not find cookie-parser
    const cookieHeader = req.headers.cookie;
    if (cookieHeader) {
        const match = cookieHeader.match(/lang=(tr|en)/);
        if (match) return match[1];
    }

    return 'tr';
}

function t(key, locale = 'tr') {
    return translations[locale][key] || key;
}

module.exports = { t, getLocale };
